QA_INFO_EXCHANGE_PROMPT = Template(
    "You are ${name}, collaborating with ${partner} to answer a multi-hop question using the private information given below.\n\n"
    "Question: ${question}\n\n"
    "Information (only visible to you):\n"
    "${information}\n\n"
    "CONVERSATION PHASES:\n"
    "1) Exploration phase:\n"
    "- First, discuss and reason TOGETHER with ${partner}.\n"
    "- Share what you see in your private information, ask clarifying questions, and propose partial hypotheses.\n"
    "- Explicitly refer to your partner's messages (e.g., \"You mentioned...\", \"From your side it seems...\").\n"
    "- IMPORTANT: In this phase, do NOT use <A>...</A> at all.\n\n"
    "2) Answer phase:\n"
    "- Only AFTER you have combined both sides of information and you are confident, you may give a final answer.\n"
    "- First, briefly summarize your reasoning in normal text (outside any tags).\n"
    "- Then, on a NEW line, output ONE final answer wrapped in <A>...</A>.\n\n"
    "GUIDELINES:\n"
    "- You may ask and answer questions freely in natural language.\n"
    "- Your private information is incomplete; you MUST actively use your partner's information. Answering only from your own view is likely to be wrong.\n"
    "- Do NOT end the conversation immediately with a final answer. Have at least a few exchanges where you and your partner share and combine evidence.\n"
    "- Always start your reply with \"${name}:\".\n\n"
    "ANSWER FORMAT RULES (final line only):\n"
    "1. The <A>...</A> tags must contain the ACTUAL final solution content.\n"
    "2. Put only the final answer inside <A>...</A>, not long reasoning. Explanations and comparisons should be written BEFORE the tags in normal text.\n"
    "3. For name/place/entity questions, output ONLY that name (e.g., <A>Solaris Array</A>).\n"
    "4. For comparison or explanation questions, make sure your normal-text reasoning includes ALL required details, then give a concise final answer inside <A>...</A>.\n"
)

