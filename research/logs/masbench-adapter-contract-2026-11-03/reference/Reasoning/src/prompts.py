# Protocol prompt with a shared blackboard.
QA_INFO_EXCHANGE_PROMPT_PROTOCOL = Template(
    # Role + task setup
    "You are ${name}, collaborating with ${partner} to answer a multi-hop question using the private information given below.\n\n"
    "Question: ${question}\n\n"
    "Information (only visible to you):\n"
    "${information}\n\n"
    "TASK:\n"
    "- Work with ${partner} to find the correct answer.\n"
    "- Think step by step about what is known and what is still missing.\n"
    "- Your private information is incomplete; you MUST actively combine it with your partner's information.\n"
    "- When you are confident, give ONE final answer wrapped in answer tags.\n\n"
    "*** SHARED BLACKBOARD MECHANISM ***:\n"
    "To help you remember, the system automatically maintains a 'Shared Knowledge Board'.\n"
    "1. **Reading**: At the end of your partner's message, you will see a summary of all previously discovered facts. TRUST this board. Do not ask questions about facts already listed there.\n"
    "2. **Writing**: Anything you write inside <R>...</R> tags will be PERMANENTLY added to this board. Use this to save key findings for the team.\n\n"
    "MESSAGE PROTOCOL (what your partner sees):\n"
    "- In each turn, include a MESSAGE block that your partner can see.\n"
    "- Start the MESSAGE block with the line:\n"
    "  \"${name}: MESSAGE\"\n"
    "- After that line, write 1-4 bullet lines. Each bullet starts with \"- \" and uses exactly ONE operator:\n"
    "  * <Q>Question Content</Q> : ask a concrete question about missing info. Be specific.\n"
    "  * <R>Fact Content</R> : provide a specific fact from your context. Make it self-contained (e.g., include entity names) so it makes sense on the Blackboard.\n"
    "  * <A>Final Answer Content</A> : propose the complete final answer. This is the ONLY place where <A> tags may appear.\n\n"
    "OPERATOR RULES:\n"
    "1. **<A> Tag Content**: \n"
    "   - Do NOT write <A>answer</A>. Write the actual content.\n"
    "   - If the answer is a name/entity, output ONLY the name.\n"
    "2. **<R> Tag Usage**: \n"
    "   - Only put VERIFIED FACTS inside <R> tags.\n"
    "   - Since these go onto the Blackboard, be precise. Instead of 'It is in 1999', write 'The event happened in 1999'.\n"
    "3. **Visibility**: Only the content inside the MESSAGE block is visible to ${partner}.\n\n"
    "FIRST TURN:\n"
    "- Your first MESSAGE must include at least one <Q>...</Q>.\n"
    "- Do NOT use <A> in your first MESSAGE.\n\n"
    "STYLE:\n"
    "- Use concise language inside operators to save bandwidth.\n"
)
